"""
Market Data Fetcher
====================
Fetches and saves:
  1. nifty50_monthly.csv    — Nifty 50 monthly returns
  2. india_vix_monthly.csv  — India VIX monthly average
  3. factors_monthly.csv    — MKT factor (Nifty excess return over RBI rate)
                              NOTE: SMB/HML/MOM not publicly available for India.
                              MKT-RF is used as a single market factor (CAPM alpha).

Sources:
  - Nifty 50 + India VIX : Yahoo Finance via yfinance (free, no API key)
  - Risk-free rate        : 91-day T-bill proxy via RBI (or fixed 6% fallback)

Requirements:
    pip install yfinance pandas requests

Run:
    python fetch_market_data.py
"""

import pandas as pd
import requests
import warnings
import logging
from datetime import date

warnings.filterwarnings("ignore")

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)s  %(message)s",
    datefmt="%H:%M:%S"
)
log = logging.getLogger(__name__)

# ─────────────────────────────────────────
# CONFIG
# ─────────────────────────────────────────
START_DATE = "2020-01-01"
END_DATE   = date.today().strftime("%Y-%m-%d")

OUT_NIFTY   = "nifty50_monthly.csv"
OUT_VIX     = "india_vix_monthly.csv"
OUT_FACTORS = "factors_monthly.csv"

# Fallback annual risk-free rate if RBI scrape fails (%)
RF_FALLBACK_ANNUAL = 6.0


# ─────────────────────────────────────────
# STEP 1: Nifty 50 monthly returns
# ─────────────────────────────────────────
def fetch_nifty50():
    log.info("Fetching Nifty 50 from Yahoo Finance ...")
    try:
        import yfinance as yf
    except ImportError:
        raise ImportError("Run: pip install yfinance")

    ticker = yf.Ticker("^NSEI")
    df = ticker.history(start=START_DATE, end=END_DATE, interval="1mo")

    if df.empty:
        raise ValueError("No Nifty 50 data returned. Check internet connection.")

    # Month-end close price
    df.index = df.index.to_period("M")
    monthly_close = df["Close"].sort_index()

    # Monthly % return
    monthly_return = monthly_close.pct_change() * 100
    monthly_return = monthly_return.dropna()
    monthly_return.name = "Nifty50_Return"
    monthly_return.index.name = "Month"

    monthly_return = monthly_return.round(4)
    monthly_return.to_csv(OUT_NIFTY, header=True)
    log.info(f"  Saved {OUT_NIFTY} ({len(monthly_return)} months, "
             f"{monthly_return.index[0]} → {monthly_return.index[-1]})")
    return monthly_return, monthly_close


# ─────────────────────────────────────────
# STEP 2: India VIX monthly average
# ─────────────────────────────────────────
def fetch_india_vix():
    log.info("Fetching India VIX from Yahoo Finance ...")
    try:
        import yfinance as yf
    except ImportError:
        raise ImportError("Run: pip install yfinance")

    ticker = yf.Ticker("^INDIAVIX")
    df = ticker.history(start=START_DATE, end=END_DATE, interval="1mo")

    if df.empty:
        # Fallback: daily data resampled
        log.warning("  Monthly VIX fetch failed, trying daily ...")
        ticker = yf.Ticker("^INDIAVIX")
        df_daily = ticker.history(start=START_DATE, end=END_DATE, interval="1d")
        if df_daily.empty:
            raise ValueError("No India VIX data returned.")
        df_daily.index = pd.DatetimeIndex(df_daily.index).to_period("M")
        df = df_daily.groupby(df_daily.index)["Close"].mean().to_frame("Close")
    else:
        df.index = df.index.to_period("M")

    vix_monthly = df["Close"].sort_index()
    vix_monthly.name = "VIX"
    vix_monthly.index.name = "Month"
    vix_monthly = vix_monthly.round(4)
    vix_monthly.to_csv(OUT_VIX, header=True)
    log.info(f"  Saved {OUT_VIX} ({len(vix_monthly)} months, "
             f"{vix_monthly.index[0]} → {vix_monthly.index[-1]})")
    log.info(f"  VIX range: {vix_monthly.min():.1f} – {vix_monthly.max():.1f}")
    return vix_monthly


# ─────────────────────────────────────────
# STEP 3: Risk-free rate (91-day T-bill)
# ─────────────────────────────────────────
def fetch_rbi_tbill_rate():
    """
    Tries to fetch 91-day T-bill rate from RBI DBIE.
    Falls back to a fixed rate if unavailable.
    Returns monthly risk-free rate (%) as a Series indexed by Period(M).
    """
    log.info("Fetching 91-day T-bill rate from RBI DBIE ...")
    try:
        url = (
            "https://dbie.rbi.org.in/DBIE/dbie.rbi?site=publications#!2"
        )
        # RBI DBIE doesn't have a clean public API — use a known CSV endpoint
        # Alternate: use a hardcoded approximate path for T-bill data
        # Since RBI DBIE requires login/session for bulk data, we use Yahoo Finance
        # to get India's 91-day T-bill via the proxy ticker INDIRBIRATE=X or fallback
        import yfinance as yf
        # IBFD (India risk-free) proxy — not always available on Yahoo
        tbill = yf.Ticker("INDIRBIRATE=X")
        hist = tbill.history(start=START_DATE, end=END_DATE)
        if hist.empty:
            raise ValueError("RBI rate not on Yahoo Finance")
        hist.index = pd.DatetimeIndex(hist.index).to_period("M")
        rf_monthly = hist.groupby(hist.index)["Close"].mean()
        rf_monthly = rf_monthly / 12  # annualised → monthly
        log.info("  RBI T-bill rate: fetched from Yahoo Finance")
        return rf_monthly

    except Exception as e:
        log.warning(f"  Could not fetch RBI rate ({e}). "
                    f"Using fixed {RF_FALLBACK_ANNUAL}% p.a. fallback.")
        # Build a flat monthly risk-free rate series
        months = pd.period_range(start=START_DATE[:7], end=END_DATE[:7], freq="M")
        rf_monthly = pd.Series(
            RF_FALLBACK_ANNUAL / 12,   # monthly rate
            index=months,
            name="RF"
        )
        return rf_monthly


# ─────────────────────────────────────────
# STEP 4: Build factors_monthly.csv
# ─────────────────────────────────────────
def build_factors(nifty_return, rf_monthly):
    """
    Constructs factors_monthly.csv with columns:
      Month | MKT | RF

    MKT = Nifty50_Return - RF  (excess market return)

    NOTE ON SMB / HML / MOM:
    India-specific Fama-French factors are NOT publicly available for free.
    For an Indian MF persistence study, using MKT alone (CAPM alpha) is
    standard practice. If you have access to CMIE Prowess or Bloomberg,
    you can construct SMB/HML/MOM and add them as columns here.
    """
    log.info("Building factors_monthly.csv ...")

    # Align indices
    common = nifty_return.index.intersection(rf_monthly.index)
    nifty_aligned = nifty_return.reindex(common)
    rf_aligned    = rf_monthly.reindex(common)

    factors = pd.DataFrame({
        "MKT": (nifty_aligned - rf_aligned).round(4),
        "RF":  rf_aligned.round(4),
    }, index=common)
    factors.index.name = "Month"

    # Placeholder columns — fill with NaN so the analysis script knows
    # they are absent without crashing
    factors["SMB"] = float("nan")
    factors["HML"] = float("nan")
    factors["MOM"] = float("nan")

    factors.to_csv(OUT_FACTORS)
    log.info(f"  Saved {OUT_FACTORS} ({len(factors)} months)")
    log.info("  NOTE: SMB/HML/MOM are NaN — only MKT factor is available.")
    log.info("        The analysis pipeline will run CAPM alpha (1-factor model).")
    return factors


# ─────────────────────────────────────────
# MAIN
# ─────────────────────────────────────────
def main():
    log.info("=" * 60)
    log.info("Market Data Fetcher")
    log.info(f"  Window: {START_DATE} → {END_DATE}")
    log.info("=" * 60)

    # Nifty 50
    nifty_return, _ = fetch_nifty50()

    # India VIX
    fetch_india_vix()

    # Risk-free rate
    rf_monthly = fetch_rbi_tbill_rate()

    # Factors
    factors = build_factors(nifty_return, rf_monthly)

    print("\n" + "=" * 55)
    print("DONE — Files saved:")
    print(f"  {OUT_NIFTY}")
    print(f"  {OUT_VIX}")
    print(f"  {OUT_FACTORS}")
    print()
    print("Factor coverage:")
    print(f"  MKT  : available ({factors['MKT'].notna().sum()} months)")
    print(f"  RF   : available ({factors['RF'].notna().sum()} months)")
    print(f"  SMB  : NOT AVAILABLE (requires CMIE Prowess / Bloomberg)")
    print(f"  HML  : NOT AVAILABLE (requires CMIE Prowess / Bloomberg)")
    print(f"  MOM  : NOT AVAILABLE (requires CMIE Prowess / Bloomberg)")
    print()
    print("The persistence analysis will use CAPM alpha (MKT only).")
    print("This is standard for Indian MF persistence studies.")


if __name__ == "__main__":
    main()