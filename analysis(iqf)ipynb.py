# MAIN
# ─────────────────────────────────────────
def main():
    print("=" * 60)
    print("MF Persistence Analysis Pipeline")
    print(f"Ranking window : {RANKING_WINDOW} months")
    print(f"Holding window : {HOLDING_WINDOW} months")
    print(f"Quintiles      : {N_QUINTILES}")
    print("=" * 60)

    # Ensure results directory exists
    os.makedirs(RESULTS_DIR, exist_ok=True)

    # Load
    df_wide, nifty, vix, factors = load_data()

    # Regimes
    print("\nDefining market regimes ...")
    regimes = define_regimes(df_wide, nifty, vix)
    regimes.to_csv(f"{RESULTS_DIR}/market_regimes.csv")

    # Return measures
    measures = {"raw": df_wide}

    df_bm = compute_bm_adjusted(df_wide, nifty)
    if df_bm is not None:
        measures["benchmark_adjusted"] = df_bm
        print("  Benchmark-adjusted returns: ready")
    else:
        print("  Benchmark-adjusted returns: SKIPPED (no Nifty data)")

    print("  Computing factor alphas (this may take a few minutes) ...")
    df_alpha = compute_factor_alpha(df_wide, factors)
    if df_alpha is not None:
        measures["factor_alpha"] = df_alpha
        print("  Factor-adjusted alpha: ready")
    else:
        print("  Factor-adjusted alpha: SKIPPED (no factor data or statsmodels)")

    # Run analysis for each measure
    all_transitions = {}
    all_avg_returns  = {}
    regression_rows  = []

    for measure_label, ret_df in measures.items():
        print(f"\n{'─'*50}")
        print(f"Analysing: {measure_label.upper()}")
        print(f"{'─'*50}")

        # Rolling quintiles
        print("  Computing rolling quintiles ...")
        quint_df = compute_rolling_quintiles(ret_df, label=measure_label)
        print(f"  Fund-period observations: {len(quint_df):,}")

        # Full-sample transition matrix
        tm, counts = build_transition_matrix(quint_df, label=measure_label)
        all_transitions[measure_label] = tm
        tm.to_csv(f"{RESULTS_DIR}/transition_matrix_{measure_label}.csv")
        print(f"\n  Transition matrix ({measure_label}):")
        print(tm.to_string())

        # Quintile average returns
        avg_rets, spread = quintile_avg_returns(quint_df)
        all_avg_returns[measure_label] = avg_rets
        avg_rets.to_csv(f"{RESULTS_DIR}/quintile_returns_{measure_label}.csv")
        print(f"\n  Quintile avg forward returns ({measure_label}):")
        print(avg_rets.to_string())
        print(f"  Q5−Q1 spread: {spread:.4f}% per month")

        # Regression
        reg = run_persistence_regression(quint_df, label=measure_label)
        if reg:
            regression_rows.append(reg)

        # Per-regime
        print(f"\n  Regime-level analysis ({measure_label}):")
        regime_res = regime_analysis(quint_df, regimes, label=measure_label)
        for regime, res in regime_res.items():
            res["transition"].to_csv(
                f"{RESULTS_DIR}/transition_matrix_{measure_label}_{regime}.csv"
            )
            if not res["avg_returns"].empty:
                res["avg_returns"].to_csv(
                    f"{RESULTS_DIR}/quintile_returns_{measure_label}_{regime}.csv"
                )

    # Regression summary
    if regression_rows:
        reg_df = pd.DataFrame(regression_rows)
        reg_df.to_csv(f"{RESULTS_DIR}/regression_results.csv", index=False)
        print(f"\n{'─'*50}")
        print("REGRESSION RESULTS (FwdReturn ~ PastReturn)")
        print(f"{'─'*50}")
        print(reg_df.to_string(index=False))

    # ── Text summary report ──
    report_lines = [
        "MUTUAL FUND PERSISTENCE ANALYSIS — SUMMARY REPORT",
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"Ranking window: {RANKING_WINDOW}M | Holding window: {HOLDING_WINDOW}M",
        "=" * 60,
        "",
        "RETURN MEASURES ANALYSED:",
    ]
    for m in measures:
        report_lines.append(f"  - {m}")

    report_lines += ["", "FULL-SAMPLE TRANSITION MATRICES:", ""]
    for m, tm in all_transitions.items():
        report_lines.append(f"  [{m}]")
        report_lines.append(tm.to_string())
        report_lines.append("")

    report_lines += ["Q5−Q1 SPREAD SUMMARY (avg monthly fwd return):"]
    for m, avg in all_avg_returns.items():
        if avg.empty or "Q5" not in avg.index or "Q1" not in avg.index:
            report_lines.append(f"  {m:30s}: N/A (insufficient data)")
            continue
        q5 = avg.loc["Q5", "Avg Fwd Monthly Return (%)"]
        q1 = avg.loc["Q1", "Avg Fwd Monthly Return (%)"]
        report_lines.append(f"  {m:30s}: {q5-q1:+.4f}% / month")

    if regression_rows:
        report_lines += ["", "REGRESSION — PERSISTENCE BETA (β):"]
        for r in regression_rows:
            report_lines.append(
                f"  {r['Measure']:30s}: β={r['Beta']:+.4f}, p={r['p_value']:.4f}, "
                f"R²={r['R_squared']:.4f}, Significant={r['Significant']}"
            )

    report_path = f"{RESULTS_DIR}/summary_report.txt"
    with open(report_path, "w") as f:
        f.write("\n".join(report_lines))

    print(f"\n{'='*60}")
    print("ALL DONE")
    print(f"{'='*60}")
    print(f"Output folder: {RESULTS_DIR}/")
    for fname in sorted(os.listdir(RESULTS_DIR)):
        print(f"  {fname}")


if __name__ == "__main__":
    main()